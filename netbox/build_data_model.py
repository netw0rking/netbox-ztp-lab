# Generic device type for devices with no modeled NOS platform.
GENERIC_MANUFACTURER = {"name": "Generic", "slug": "generic"}
GENERIC_DEVICE_TYPE = {"model": "Generic Host (virtual)", "slug": "generic-host-virtual"}


def _device_type_for(nb, platform_slug, manufacturer_id):
    spec = DEVICE_TYPE_DEFS[platform_slug]
    return get_or_create(
        nb.dcim.device_types,
        {"slug": spec["slug"]},
        defaults={"model": spec["model"], "manufacturer": manufacturer_id},
    )


def _generic_device_type(nb):
    manufacturer = get_or_create(
        nb.dcim.manufacturers,
        {"slug": GENERIC_MANUFACTURER["slug"]},
        defaults={"name": GENERIC_MANUFACTURER["name"]},
    )
    return get_or_create(
        nb.dcim.device_types,
        {"slug": GENERIC_DEVICE_TYPE["slug"]},
        defaults={"model": GENERIC_DEVICE_TYPE["model"], "manufacturer": manufacturer.id},
    )


def _get_or_create_interface(nb, device, if_name, if_type="1000base-t", description=None):
    # Lookup uses device_id, but writes need the device key.
    obj = nb.dcim.interfaces.get(device_id=device.id, name=if_name)
    if obj is None:
        obj = nb.dcim.interfaces.create(
            device=device.id, name=if_name, type=if_type, description=description or ""
        )
    # Re-derive the description from connects_to on every run.
    elif description is not None and obj.description != description:
        obj.description = description
        obj.save()
    return obj


def _link_description(intf):
    connects_to = intf.get("connects_to")
    if not connects_to:
        return None
    return f"to {connects_to['device']} {connects_to['interface']}"


def build_devices(nb, data, schema):
    site = schema["site"]
    roles = schema["roles"]
    platforms = schema["platforms"]
    devices = {}

    for name, dev in data["devices"].items():
        role = roles[dev["role"]]
        platform = platforms.get(dev.get("platform"))
        if platform is not None:
            device_type = _device_type_for(nb, dev["platform"], platform.manufacturer.id)
        else:
            device_type = _generic_device_type(nb)

        device_defaults = {"site": site.id, "role": role.id, "device_type": device_type.id}
        if platform is not None:
            device_defaults["platform"] = platform.id

        device = get_or_create(nb.dcim.devices, {"name": name}, defaults=device_defaults)

        # get_or_create skips defaults on existing devices, so reconcile here.
        needs_save = False
        if device.role.id != role.id:
            device.role = role.id
            needs_save = True
        if device.device_type.id != device_type.id:
            device.device_type = device_type.id
            needs_save = True
        current_platform_id = device.platform.id if device.platform else None
        wanted_platform_id = platform.id if platform is not None else None
        if current_platform_id != wanted_platform_id:
            device.platform = wanted_platform_id
            needs_save = True
        if needs_save:
            device.save()

        custom_fields = {}
        if "bgp_asn" in dev:
            custom_fields["bgp_asn"] = dev["bgp_asn"]
        if "serial_number" in dev:
            custom_fields["serial_number"] = dev["serial_number"]
        if "overlay_vlan_id" in dev:
            custom_fields["overlay_vlan_id"] = dev["overlay_vlan_id"]
        if "overlay_vni" in dev:
            custom_fields["overlay_vni"] = dev["overlay_vni"]
        if "overlay_test_ip" in dev:
            custom_fields["overlay_test_ip"] = dev["overlay_test_ip"]
        if "l3vni" in dev:
            custom_fields["l3vni"] = dev["l3vni"]
        if "vrf_name" in dev:
            custom_fields["vrf_name"] = dev["vrf_name"]
        if "default_gw" in dev:
            custom_fields["default_gw"] = dev["default_gw"]
        if "net" in dev:
            custom_fields["net"] = dev["net"]
        if "backbone_peers" in dev:
            custom_fields["backbone_peers"] = dev["backbone_peers"]
        if "route_reflector" in dev:
            custom_fields["route_reflector"] = dev["route_reflector"]
        if "vendor_image" in dev:
            custom_fields["vendor_image"] = dev["vendor_image"]
        if "srv6_locator" in dev:
            custom_fields["srv6_locator"] = dev["srv6_locator"]
        if "sr_policies" in dev:
            custom_fields["sr_policies"] = dev["sr_policies"]
        if "sr_index" in dev:
            custom_fields["sr_index"] = dev["sr_index"]
        if custom_fields:
            device.custom_fields.update(custom_fields)
            device.save()

        interfaces = {}
        dev_interfaces = dev.get("interfaces", {})
        wanted_if_names = set(dev_interfaces)
        for if_name in wanted_if_names:
            description = _link_description(dev_interfaces[if_name])
            interfaces[if_name] = _get_or_create_interface(nb, device, if_name, description=description)

        # Remove stale interfaces; skip Loopback0/mgmt0/Vlan1 placeholders.
        PLACEHOLDER_IF_NAMES = {"Loopback0", "mgmt0", "Vlan1"}
        for existing_if in nb.dcim.interfaces.filter(device_id=device.id):
            if existing_if.name in wanted_if_names or existing_if.name in PLACEHOLDER_IF_NAMES:
                continue
            # Delete the cable first; interface deletion does not cascade.
            cable_id = getattr(existing_if, "cable", None)
            if cable_id:
                nb.dcim.cables.get(id=cable_id.id).delete()
            existing_if.delete()

        devices[name] = {"device": device, "interfaces": interfaces}

        _assign_ips(nb, device, interfaces, dev)

    return devices


def _get_or_create_ip(nb, address, description):
    # Always converge the description, even for pre-existing IPs.
    ip = nb.ipam.ip_addresses.get(address=address)
    if ip is None:
        return nb.ipam.ip_addresses.create(address=address, status="active", description=description)
    if ip.description != description:
        ip.description = description
        ip.save()
    return ip


def _assign_ips(nb, device, interfaces, dev):
    if "loopback" in dev:
        # Loopback needs an interface to be primary; use a placeholder.
        loopback_intf = _get_or_create_interface(nb, device, "loopback0", if_type="virtual")
        ip = _get_or_create_ip(nb, dev["loopback"], f"{device.name} loopback0")
        ip.assigned_object_type = "dcim.interface"
        ip.assigned_object_id = loopback_intf.id
        ip.save()
        device.primary_ip4 = ip.id
        device.save()

    if "oob_svi_ip" in dev:
        # Vlan1 IP is assigned to a real SVI interface.
        svi_intf = _get_or_create_interface(nb, device, "Vlan1", if_type="virtual")
        ip = _get_or_create_ip(nb, dev["oob_svi_ip"], f"{device.name} Vlan1 (OOB SVI)")
        ip.assigned_object_type = "dcim.interface"
        ip.assigned_object_id = svi_intf.id
        ip.save()

    if "mgmt_ip" in dev:
        # mgmt0 is a placeholder; nothing cables to it.
        mgmt_intf = _get_or_create_interface(nb, device, "mgmt0", if_type="virtual")
        ip = _get_or_create_ip(nb, dev["mgmt_ip"], f"{device.name} mgmt0 (containerlab mgmt network)")
        ip.assigned_object_type = "dcim.interface"
        ip.assigned_object_id = mgmt_intf.id
        ip.save()

    for if_name, intf in dev.get("interfaces", {}).items():
        ip_cidr = intf.get("ip")
        if not ip_cidr:
            continue
        ip = _get_or_create_ip(nb, ip_cidr, f"{device.name} {if_name}")
        ip.assigned_object_type = "dcim.interface"
        ip.assigned_object_id = interfaces[if_name].id
        ip.save()


def build_cables(nb, data, devices):
    seen = set()
    for name, dev in data["devices"].items():
        for if_name, intf in dev.get("interfaces", {}).items():
            connects_to = intf.get("connects_to")
            if not connects_to:
                continue
            peer_name = connects_to["device"]
            peer_if_name = connects_to["interface"]
            key = frozenset({(name, if_name), (peer_name, peer_if_name)})
            if key in seen:
                continue
            seen.add(key)

            a_iface = devices[name]["interfaces"][if_name]

            # Peer may belong to another site; look it up in NetBox.
            if peer_name in devices:
                b_iface = devices[peer_name]["interfaces"][peer_if_name]
            else:
                peer_device = nb.dcim.devices.get(name=peer_name)
                if peer_device is None:
                    continue
                b_iface = next(
                    (
                        iface
                        for iface in nb.dcim.interfaces.filter(device_id=peer_device.id)
                        if iface.name == peer_if_name
                    ),
                    None,
                )
                if b_iface is None:
                    continue

            # Check cable on each interface, so either side order matches.
            if getattr(a_iface, "cable", None) or getattr(b_iface, "cable", None):
                continue

            nb.dcim.cables.create(
                a_terminations=[{"object_type": "dcim.interface", "object_id": a_iface.id}],
                b_terminations=[{"object_type": "dcim.interface", "object_id": b_iface.id}],
            )


